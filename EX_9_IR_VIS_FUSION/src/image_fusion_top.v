// ============================================================================
// MODULE: image_fusion_top
// DESCRIPTION: Unified top-level for the OV5640 VIS camera and the VIGIL80 IR camera
//
// Current development stage:
// - both cameras are acquired independently;
// - both cameras use their own double framebuffer;
// - both read banks are updated only at the beginning of an HDMI frame;
// - a compile-time debug parameter selects which image is sent to HDMI.
//
// CLOCK NOTE:
// Based on the board clock (27MHz), the circuit requires:
// - clk_pixel;
// - clk_tmds = 5 * clk_pixel.
//
// On the Tang Nano 9K, these clocks are generated by the Gowin rPLL and
// CLKDIV primitives.
// ============================================================================
module image_fusion_top #(

    // ========================================================================
    // Temporary source selection used before implementing image fusion
    // ========================================================================
    //
    // DEBUG_SOURCE = 0:
    //     display the OV5640 visible image.
    //
    // DEBUG_SOURCE = 1:
    //     display the VIGIL80 false-colour thermal image.
    //
    // This is a compile-time parameter and therefore does not require an
    // additional physical input pin.
    //
    // When fusion_pipeline is implemented, this parameter can be replaced by
    // a wider display mode:
    //
    // 00 = visible
    // 01 = thermal grayscale
    // 10 = thermal false-colour
    // 11 = fused image
    // ========================================================================

    parameter bit DEBUG_SOURCE = 1'b1,

    // Horizontal parameters (Pixel)
    // | ACTIVE | FRONT | SYNC | BACK |
    parameter int H_ACTIVE = 640,
    parameter int H_FRONT  = 16,
    parameter int H_SYNC   = 96,
    parameter int H_BACK   = 48,

    parameter int H_TOTAL = H_ACTIVE + H_FRONT + H_SYNC + H_BACK, // 800

    // Vertical parameters (Lines)
    // | ACTIVE | FRONT | SYNC | BACK |
    parameter int V_ACTIVE = 480,
    parameter int V_FRONT  = 10,
    parameter int V_SYNC   = 2,
    parameter int V_BACK   = 33,

    parameter int V_TOTAL = V_ACTIVE + V_FRONT + V_SYNC + V_BACK, // 525

    // Polarity
    parameter bit H_SYNC_POL = 1'b0,
    parameter bit V_SYNC_POL = 1'b0,

    // Needed bits to correctly count pixels and lines
    parameter int H_BITS = $clog2(H_TOTAL),
    parameter int V_BITS = $clog2(V_TOTAL)

)(
    input logic rst_n,       // Asynchronous reset active low
    input logic clk_27MHz,   // Tang Nano 9K board clock

    // ========================================================================
    // OV5640 visible-camera interface
    // ========================================================================

    input  logic       ov_pclk,
    input  logic       ov_vsync,
    input  logic       ov_href,
    input  logic [7:0] ov_data,

    output logic       ov_reset_n,
    output logic       ov_pwdn,

    inout wire         ov_scl,
    inout wire         ov_sda,

    // ========================================================================
    // VIGIL80 infrared-camera interface
    // ========================================================================

    input logic vigil_sck,   //serial clk generated by the camera
    input logic vigil_csb,   //chip select active low
    input logic vigil_mosi,  //serial thermal data from the camera to the FPGA

    // ========================================================================
    // Debug output
    // ========================================================================

    output logic debug_led,

    // ========================================================================
    // Differential HDMI outputs
    // On the Tang Nano 9K these outputs are mapped to LVCMOS33 pins
    // ========================================================================

    output logic tmds_clk_p,
    output logic tmds_clk_n,

    output logic tmds_d0_p,
    output logic tmds_d0_n, // Blue

    output logic tmds_d1_p,
    output logic tmds_d1_n, // Green

    output logic tmds_d2_p,
    output logic tmds_d2_n  // Red
);

    // ========================================================================
    // Image dimensions
    // ========================================================================

    // Visible framebuffer:
    // 160 x 120 RGB332
    localparam int VIS_W          = 160;
    localparam int VIS_H          = 120;
    localparam int VIS_FRAME_PIX  = VIS_W * VIS_H;
    localparam int VIS_ADDR_BITS  = $clog2(VIS_FRAME_PIX);

    // Infrared framebuffer:
    // 80 x 80 grayscale.
    localparam int IR_W          = 80;
    localparam int IR_H          = 80;
    localparam int IR_FRAME_PIX  = IR_W * IR_H;
    localparam int IR_ADDR_BITS  = $clog2(IR_FRAME_PIX);

    // VIGIL80 frame also contains 23 footer words that are received but are
    // not written into the image framebuffer.
    localparam int IR_FOOTER_WORDS = 23;
    localparam int IR_TOTAL_WORDS  = IR_FRAME_PIX + IR_FOOTER_WORDS;

    // ========================================================================
    // Internal HDMI/video signals
    // ========================================================================

    logic clk_pixel; // HDMI pixel clock
    logic clk_tmds;  // TMDS clock: five times clk_pixel

    logic [H_BITS-1:0] cx; // Horizontal pixel counter
    logic [V_BITS-1:0] cy; // Vertical line counter

    logic hsync, vsync, vde;

    // Final RGB values sent to the TMDS encoders.
    logic [7:0] red, green, blue;
    logic [9:0] tmds_r, tmds_g, tmds_b;

    // ========================================================================
    // Visible framebuffer read interface
    // ========================================================================

    logic [VIS_ADDR_BITS-1:0] vis_rd_addr;
    logic [7:0]               vis_rd_pixel;
    logic                     vis_rd_req;
    logic                     vis_rd_valid;

    logic vis_frame_available;
    logic vis_writing_allowed;
    logic vis_camera_initialized;

    // ========================================================================
    // Thermal framebuffer read interface
    // ========================================================================

    logic [IR_ADDR_BITS-1:0] ir_rd_addr;
    logic [7:0]              ir_rd_pixel;
    logic                    ir_rd_req;
    logic                    ir_rd_valid;

    logic ir_frame_available;
    logic ir_writing_allowed;

    // ========================================================================
    // RGB outputs generated by the temporary independent renderers
    // ========================================================================

    logic [7:0] vis_red, vis_green, vis_blue;

    logic [7:0] ir_red, ir_green, ir_blue;

    // ========================================================================
    // Common framebuffer read-swap point
    // ========================================================================
    // Therefore, during one complete HDMI frame:
    // - the visible read bank remains unchanged;
    // - the thermal read bank remains unchanged.
    //
    // Each manager may independently select its newest complete frame at the
    // next HDMI frame boundary.
    //
    // This means that the two cameras do not need to have the same frame rate.
    // The future fusion pipeline will always use:
    //
    // - the latest complete visible frame;
    // - the latest complete thermal frame.
    // ========================================================================

    logic  hdmi_frame_start;
    assign hdmi_frame_start =(cx == '0) && (cy == '0);

    // ========================================================================
    // Debug LED(active low)
    // ========================================================================
    // The LED turns on only when:
    // - the OV5640 SCCB configuration has completed;
    // - at least one visible frame is available;
    // - at least one thermal frame is available.
    // ========================================================================

    assign debug_led = ~(
        vis_camera_initialized &&
        vis_frame_available    &&
        ir_frame_available
    );

    // ========================================================================
    // Clock stage
    // ========================================================================

    Gowin_rPLL PLL (
        .clkout (clk_tmds), // Fast clock for serializer
        .reset  (~rst_n),
        .clkin  (clk_27MHz)
    );

    CLKDIV #(
        .DIV_MODE ("5"),
        .GSREN    ("false")
    ) clk_div_5 (
        .CLKOUT (clk_pixel), // Pixel clock
        .HCLKIN (clk_tmds),
        .RESETN (rst_n),
        .CALIB  (1'b0)
    );

    // ========================================================================
    // 1. Synchronisms Generator (Timings)
    // ========================================================================

    video_timing #(
        .H_ACTIVE    (H_ACTIVE),
        .H_FRONT     (H_FRONT),
        .H_SYNC      (H_SYNC),
        .H_BACK      (H_BACK),
        .H_TOTAL     (H_TOTAL),
        .H_SYNC_POL  (H_SYNC_POL),
        .H_BITS      (H_BITS),

        .V_ACTIVE    (V_ACTIVE),
        .V_FRONT     (V_FRONT),
        .V_SYNC      (V_SYNC),
        .V_BACK      (V_BACK),
        .V_TOTAL     (V_TOTAL),
        .V_SYNC_POL  (V_SYNC_POL),
        .V_BITS      (V_BITS)
    ) timing_inst (
        .clk    (clk_pixel),
        .rst_n  (rst_n),
        .cx     (cx),
        .cy     (cy),
        .hsync  (hsync),
        .vsync  (vsync),
        .vde    (vde)
    );

    // ========================================================================
    // 2. VIS camera manager
    // ========================================================================
    // The visible manager:
    // - initializes the OV5640 through SCCB;
    // - receives a 160 x 120 RGB565 DVP stream;
    // - converts RGB565 into RGB332;
    // - stores complete frames in the VIS double framebuffer;
    // - exposes the stable read bank through the read interface below.
    //
    // A Gowin_SDP_VIS IP from IP Catalog must be generated with:
    // data width:    8 bit
    // depth:         19200
    // address width: 15 bit
    // ========================================================================

    ov5640_visible_manager #(
        .IMG_W      (VIS_W),
        .IMG_H      (VIS_H),
        .FRAME_PIX  (VIS_FRAME_PIX),
        .ADDR_BITS  (VIS_ADDR_BITS)
    ) visible_camera_inst (
        .rst_n               (rst_n),
        .sys_clk             (clk_27MHz),

        .ov_pclk             (ov_pclk),
        .ov_vsync            (ov_vsync),
        .ov_href             (ov_href),
        .ov_data             (ov_data),

        .ov_reset_n          (ov_reset_n),   //different reset required for camera configuration
        .ov_pwdn             (ov_pwdn),

        .ov_scl              (ov_scl),
        .ov_sda              (ov_sda),

        // Read side: HDMI/fusion clock domain
        .rd_clk              (clk_pixel),
        .rd_swap_point       (hdmi_frame_start),
        .rd_req              (vis_rd_req),
        .rd_addr             (vis_rd_addr),
        .rd_pixel            (vis_rd_pixel),
        .rd_valid            (vis_rd_valid),

        .camera_initialized  (vis_camera_initialized),
        .frame_available     (vis_frame_available),
        .writing_allowed     (vis_writing_allowed)
    );

    // ========================================================================
    // 3. IR camera manager
    // ========================================================================
    // The infrared manager:
    // - receives the 16-bit serial thermal stream;
    // - discards the 23 footer words;
    // - converts each 16-bit thermal value into an 8-bit normalized intensity;
    // - stores complete 80 x 80 frames in the IR double framebuffer;
    // - exposes the stable read bank through the read interface below.

    // A Gowin_SDP_IR IP from IP Catalog must be generated with:
    // data width:    8 bit
    // depth:         6400
    // address width: 13 bit
    // ========================================================================
    
    // Thermal conversion parameters
    localparam int TEMP_MIN = 16'd27315; // Minimum Temp used as reference for conversion. 
                                         // TEMP_MIN = 27315 means about 0 °C in Kelvin x100
    localparam int TEMP_SHIFT = 5;       //implements division by 32 by means of a right shift.
  
    vigil80_ir_manager #(
        .IMG_W         (IR_W),
        .IMG_H         (IR_H),
        .FRAME_PIX     (IR_FRAME_PIX),
        .FOOTER_WORDS  (IR_FOOTER_WORDS),
        .TOTAL_WORDS   (IR_TOTAL_WORDS),
        .ADDR_BITS     (IR_ADDR_BITS),

        .TEMP_MIN      (TEMP_MIN),
        .TEMP_SHIFT    (TEMP_SHIFT)
    ) vigil80_manager_inst (
        .rst_n            (rst_n),

        .vigil_sck        (vigil_sck),
        .vigil_csb        (vigil_csb),
        .vigil_mosi       (vigil_mosi),

        // Read side: HDMI/fusion clock domain
        .rd_clk           (clk_pixel),
        .rd_swap_point    (hdmi_frame_start),
        .rd_req           (ir_rd_req),
        .rd_addr          (ir_rd_addr),
        .rd_pixel         (ir_rd_pixel),
        .rd_valid         (ir_rd_valid),

        .frame_available  (ir_frame_available),
        .writing_allowed  (ir_writing_allowed)
    );

    // ========================================================================
    // 4. Temporary VIS image renderer
    // ========================================================================
    // This renderer is retained temporarily to verify the combined top-level.
    //
    // The visible image is already stored as 160 x 120 and is scaled by four:
    // 160 x 4 = 640
    // 120 x 4 = 480
    //
    // Therefore the visible image fills the complete active HDMI area.
    //
    // This module will later be replaced by fusion_pipeline.
    // ========================================================================

    visible_hdmi_renderer_rgb332 #(
        .H_ACTIVE   (H_ACTIVE),
        .V_ACTIVE   (V_ACTIVE),
        .H_BITS     (H_BITS),
        .V_BITS     (V_BITS),

        .IMG_W      (VIS_W),
        .IMG_H      (VIS_H),

        .SCALE      (4),

        .FRAME_PIX  (VIS_FRAME_PIX),
        .ADDR_BITS  (VIS_ADDR_BITS)
    ) visible_renderer_inst (
        .clk_pixel  (clk_pixel),
        .rst_n      (rst_n),

        .cx         (cx),
        .cy         (cy),
        .vde        (vde),

        .rd_req     (vis_rd_req),
        .rd_addr    (vis_rd_addr),
        .rd_pixel   (vis_rd_pixel),
        .rd_valid   (vis_rd_valid),

        .red        (vis_red),
        .green      (vis_green),
        .blue       (vis_blue)
    );

    // ========================================================================
    // 5. Temporary IR image renderer
    // ========================================================================
    // This renderer is also retained temporarily to verify the combined
    // top-level before adding spatial alignment and image fusion.
    //
    // The thermal image is currently displayed with SCALE = 6:
    // 80 x 6 = 480
    // 80 x 6 = 480
    //
    // The 480 x 480 thermal image is centered horizontally inside the
    // 640 x 480 HDMI frame.
    //
    // In the future this module will be replaced by:
    //
    // IR framebuffer
    //      |
    //      +--> thermal saliency
    //      |
    //      +--> thermal_false_color
    //                 |
    //                 +--> dynamic blending
    // ========================================================================

    thermal_hdmi_renderer #(
        .H_ACTIVE   (H_ACTIVE),
        .V_ACTIVE   (V_ACTIVE),
        .H_BITS     (H_BITS),
        .V_BITS     (V_BITS),

        .IMG_W      (IR_W),
        .IMG_H      (IR_H),

        .SCALE      (6),

        .FRAME_PIX  (IR_FRAME_PIX),
        .ADDR_BITS  (IR_ADDR_BITS)
    ) thermal_renderer_inst (
        .clk_pixel  (clk_pixel),
        .rst_n      (rst_n),

        .cx         (cx),
        .cy         (cy),
        .vde        (vde),

        .rd_req     (ir_rd_req),
        .rd_addr    (ir_rd_addr),
        .rd_pixel   (ir_rd_pixel),
        .rd_valid   (ir_rd_valid),

        .red        (ir_red),
        .green      (ir_green),
        .blue       (ir_blue)
    );

    // ========================================================================
    // 6. Temporary output selector
    // ========================================================================
    // This combinational multiplexer allows the new unified top-level to be
    // tested before fusion_pipeline is implemented.
    //
    // DEBUG_SOURCE = 0:
    //     the HDMI output displays the visible image.
    //
    // DEBUG_SOURCE = 1:
    //     the HDMI output displays the thermal false-colour image.
    //
    // Both camera managers and both framebuffer systems remain active
    // regardless of which source is displayed.
    //
    // This is useful because it verifies that:
    // - both cameras are simultaneously acquiring frames;
    // - both double framebuffer protocols are running;
    // - both read banks are updated at hdmi_frame_start;
    // - the selected image is correctly sent to HDMI.
    //
    // FUTURE REPLACEMENT:
    //
    // The following multiplexer will later receive the RGB output generated
    // by fusion_pipeline.
    // ========================================================================

    always_comb begin
        if (DEBUG_SOURCE == 1'b0) begin
            red   = vis_red;
            green = vis_green;
            blue  = vis_blue;
        end
        else begin
            red   = ir_red;
            green = ir_green;
            blue  = ir_blue;
        end
    end

    // ========================================================================
    // FUTURE IMAGE-FUSION PIPELINE CONNECTION
    // ========================================================================
    //
    // When the two input chains have been verified in this unified top-level,
    // the two temporary renderer instances should be replaced with a module
    // having an interface conceptually similar to:
    //
    // fusion_pipeline fusion_pipeline_inst (
    //     .clk_pixel          (clk_pixel),
    //     .rst_n              (rst_n),
    //
    //     .cx                 (cx),
    //     .cy                 (cy),
    //     .vde                (vde),
    //
    //     .vis_rd_req         (vis_rd_req),
    //     .vis_rd_addr        (vis_rd_addr),
    //     .vis_rd_pixel       (vis_rd_pixel),
    //     .vis_rd_valid       (vis_rd_valid),
    //
    //     .ir_rd_req          (ir_rd_req),
    //     .ir_rd_addr         (ir_rd_addr),
    //     .ir_rd_pixel        (ir_rd_pixel),
    //     .ir_rd_valid        (ir_rd_valid),
    //
    //     .red                (red),
    //     .green              (green),
    //     .blue               (blue),
    //     .pixel_valid        (fusion_pixel_valid)
    // );
    //
    // The fusion module will perform:
    //
    // 1. Visible framebuffer address generation.
    // 2. Thermal scaling 80 x 80 -> 160 x 160 by coordinate shifts.
    // 3. Vertical crop to obtain a 160 x 120 thermal region.
    // 4. Spatial X/Y alignment.
    // 5. RGB332 -> RGB888 visible conversion.
    // 6. Thermal false-colour mapping.
    // 7. Thermal saliency.
    // 8. Visible saliency.
    // 9. Dynamic alpha selection.
    // 10. Shift/add alpha blending.
    // ========================================================================

    // =========================================================================
    // 7. TMDS ENCODER SECTION
    // =========================================================================

    // -------------------------------------------------------------------------
    // Pipeline alignment delay
    // -------------------------------------------------------------------------
    // The current independent renderers have the same effective latency used
    // by the two original architectures.
    //
    // IMPORTANT:
    // When fusion_pipeline is inserted, this delay must be increased so that
    // hsync, vsync and vde remain aligned with the final fused RGB pixel.
    // -------------------------------------------------------------------------

    logic [1:0] hsync_d, vsync_d, vde_d_top;

    always_ff @(posedge clk_pixel or negedge rst_n) begin
        if (!rst_n) begin
            hsync_d    <= 2'b00;
            vsync_d    <= 2'b00;
            vde_d_top  <= 2'b00;
        end
        else begin
            hsync_d    <= {hsync_d[0], hsync};
            vsync_d    <= {vsync_d[0], vsync};
            vde_d_top  <= {vde_d_top[0], vde};
        end
    end

    // Encoders TMDS
    tmds_encoder enc_b (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (blue),
        .ctrl      ({vsync_d[1], hsync_d[1]}), // The blue channel carries HSYNC and VSYNC during blanking, when vde = 0
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_b)
    );

    tmds_encoder enc_g (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (green),
        .ctrl      (2'b00),
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_g)
    );

    tmds_encoder enc_r (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (red),
        .ctrl      (2'b00),
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_r)
    );

    // ========================================================================
    // 8. Serializer 10:1
    // ========================================================================
    // The TMDS clock is serialized using the fixed pattern 1111100000.
    //
    // The Gowin OSER10 primitive uses:
    // - PCLK = pixel clock;
    // - FCLK = TMDS clock, equal to 5 times the pixel clock.
    // ========================================================================

    logic s_clk;
    logic s_d0;
    logic s_d1;
    logic s_d2;

    serializer_10to1 ser_b (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_b),
        .serial_out  (s_d0)
    );

    serializer_10to1 ser_g (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_g),
        .serial_out  (s_d1)
    );

    serializer_10to1 ser_r (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_r),
        .serial_out  (s_d2)
    );

    serializer_10to1 ser_clk (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (10'b1111100000),
        .serial_out  (s_clk)
    );

    // ========================================================================
    // Differential HDMI output buffers
    // ========================================================================
    // ELVDS_OBUF is required to generate the real physical differential output
    // pairs on the Tang Nano 9K
    // ========================================================================

    ELVDS_OBUF obuf_d0 (
        .I  (s_d0),
        .O  (tmds_d0_p),
        .OB (tmds_d0_n)
    );

    ELVDS_OBUF obuf_d1 (
        .I  (s_d1),
        .O  (tmds_d1_p),
        .OB (tmds_d1_n)
    );

    ELVDS_OBUF obuf_d2 (
        .I  (s_d2),
        .O  (tmds_d2_p),
        .OB (tmds_d2_n)
    );

    ELVDS_OBUF obuf_clk (
        .I  (s_clk),
        .O  (tmds_clk_p),
        .OB (tmds_clk_n)
    );

endmodule