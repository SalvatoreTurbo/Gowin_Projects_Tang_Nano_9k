// ============================================================================
// MODULE: image_fusion_fusion_top
// DESCRIPTION: Unified top-level for the OV5640 VIS camera and the VIGIL80 IR camera.
//
// Current development stage:
// - both cameras are acquired independently;
// - both cameras use their own double framebuffer;
// - both read banks are updated only at the beginning of an HDMI frame;
// - the debug_sel button cycles the HDMI output: VIS, IR gray, 50/50 blend;
// - VIS_Y8 selects the visible format (Y8 grayscale or RGB332 colour).
//
// CLOCK NOTE:
// Based on the board clock (27MHz), the circuit requires:
// - clk_pixel;
// - clk_tmds = 5 * clk_pixel.
//
// On the Tang Nano 9K, these clocks are generated by the Gowin rPLL and
// CLKDIV primitives.
// ============================================================================
module image_fusion_fusion_top #(

    // Horizontal parameters (Pixel)
    // | ACTIVE | FRONT | SYNC | BACK |
    parameter int H_ACTIVE = 640,
    parameter int H_FRONT  = 16,
    parameter int H_SYNC   = 96,
    parameter int H_BACK   = 48,

    parameter int H_TOTAL = H_ACTIVE + H_FRONT + H_SYNC + H_BACK, // 800

    // Vertical parameters (Lines)
    // | ACTIVE | FRONT | SYNC | BACK |
    parameter int V_ACTIVE = 480,
    parameter int V_FRONT  = 10,
    parameter int V_SYNC   = 2,
    parameter int V_BACK   = 33,

    parameter int V_TOTAL = V_ACTIVE + V_FRONT + V_SYNC + V_BACK, // 525

    // Polarity
    parameter bit H_SYNC_POL = 1'b0,
    parameter bit V_SYNC_POL = 1'b0,

    // Needed bits to correctly count pixels and lines
    parameter int H_BITS = $clog2(H_TOTAL),
    parameter int V_BITS = $clog2(V_TOTAL),

    // Visible image format:
    // 1 = Y8 grayscale (OV5640 YUV422, luminance only)
    // 0 = RGB332 colour (OV5640 RGB565 converted to RGB332)
    parameter bit VIS_Y8 = 1'b1

)(
    input logic rst_n,       // Asynchronous reset active low
    input logic clk_27MHz,   // Tang Nano 9K board clock

    // ========================================================================
    // OV5640 visible-camera interface
    // ========================================================================

    input  logic       ov_pclk,
    input  logic       ov_vsync,
    input  logic       ov_href,
    input  logic [7:0] ov_data,

    output logic       ov_reset_n,
    output logic       ov_pwdn,

    inout wire         ov_scl,
    inout wire         ov_sda,

    // ========================================================================
    // VIGIL80 infrared-camera interface
    // ========================================================================

    input logic vigil_sck,   //serial clk generated by IR camera
    input logic vigil_csb,   //chip select active low
    input logic vigil_mosi,  //serial thermal data from the camera to the FPGA

    // ========================================================================
    // Debug IN/OUT
    // ========================================================================

    input logic debug_sel,  //Temporary source selection used before implementing image fusion, connected to board button
    output logic debug_led,

    // ========================================================================
    // Differential HDMI outputs
    // On the Tang Nano 9K these outputs are mapped to LVCMOS33 pins
    // ========================================================================

    output logic tmds_clk_p,
    output logic tmds_clk_n,

    output logic tmds_d0_p,
    output logic tmds_d0_n, // Blue

    output logic tmds_d1_p,
    output logic tmds_d1_n, // Green

    output logic tmds_d2_p,
    output logic tmds_d2_n  // Red
);

    // ========================================================================
    // Image dimensions
    // ========================================================================

    // Visible framebuffer:
    // 160 x 120, 8 bit: Y8 (VIS_Y8 = 1) or RGB332 (VIS_Y8 = 0)
    localparam int VIS_W          = 160;
    localparam int VIS_H          = 120;
    localparam int VIS_FRAME_PIX  = VIS_W * VIS_H;
    localparam int VIS_ADDR_BITS  = $clog2(VIS_FRAME_PIX);

    // Infrared framebuffer:
    // 80 x 80 grayscale.
    localparam int IR_W          = 80;
    localparam int IR_H          = 80;
    localparam int IR_FRAME_PIX  = IR_W * IR_H;
    localparam int IR_ADDR_BITS  = $clog2(IR_FRAME_PIX);

    // VIGIL80 frame also contains 23 footer words that are received but are
    // not written into the image framebuffer.
    localparam int IR_FOOTER_WORDS = 23;
    localparam int IR_TOTAL_WORDS  = IR_FRAME_PIX + IR_FOOTER_WORDS;

    // Vigil80 thermal conversion parameters
    localparam int TEMP_MIN = 16'd26250; // Minimum Temp used as reference for conversion. 
                                         // TEMP_MIN = 262.50 K (about -10.65 °C), values in Kelvin x100
    localparam int TEMP_SHIFT = 2;       // Implements division by 32 by means of a right shift.

    // ========================================================================
    // Internal HDMI/video signals
    // ========================================================================

    logic clk_pixel; // HDMI pixel clock
    logic clk_tmds;  // TMDS clock: 5 times clk_pixel

    logic [H_BITS-1:0] cx; // Horizontal pixel counter
    logic [V_BITS-1:0] cy; // Vertical line counter

    logic hsync, vsync, vde;

    // Final RGB values sent to the TMDS encoders.
    logic [7:0] red, green, blue;
    logic [9:0] tmds_r, tmds_g, tmds_b;

    // ========================================================================
    // Visible framebuffer read interface
    // ========================================================================

    logic [VIS_ADDR_BITS-1:0] vis_rd_addr;
    logic [7:0]               vis_rd_pixel;
    logic                     vis_rd_req;
    logic                     vis_rd_valid;

    logic vis_frame_available;
    logic vis_writing_allowed;
    logic vis_camera_initialized;

    // ========================================================================
    // Thermal framebuffer read interface
    // ========================================================================

    logic [IR_ADDR_BITS-1:0] ir_rd_addr;
    logic [7:0]              ir_rd_pixel;
    logic                    ir_rd_req;
    logic                    ir_rd_valid;

    logic ir_frame_available;
    logic ir_writing_allowed;

    // ========================================================================
    // Common framebuffer read-swap point
    // ========================================================================
    // Therefore, during one complete HDMI frame:
    // - the visible read bank remains unchanged;
    // - the thermal read bank remains unchanged.
    //
    // Each manager may independently select its newest complete frame at the
    // next HDMI frame boundary.
    //
    // This means that the two cameras do not need to have the same frame rate.
    // The future fusion pipeline will always use:
    //
    // - the latest complete visible frame;
    // - the latest complete thermal frame.
    // ========================================================================

    logic  hdmi_frame_start;
    assign hdmi_frame_start =(cx == '0) && (cy == '0);

    // ========================================================================
    // Debug LED(active low)
    // ========================================================================
    // The LED turns on only when:
    // - the OV5640 SCCB configuration has completed;
    // - at least one visible frame is available;
    // - at least one thermal frame is available.
    // ========================================================================

//    assign debug_led = ~(
//        vis_camera_initialized &&
//        vis_frame_available    &&
//        ir_frame_available
//    );
assign debug_led = ~vis_frame_available;

    // ========================================================================
    // Clock stage
    // ========================================================================

    Gowin_rPLL PLL (
        .clkout (clk_tmds), // Fast clock for serializer
        .reset  (~rst_n),
        .clkin  (clk_27MHz)
    );

    CLKDIV #(
        .DIV_MODE ("5"),
        .GSREN    ("false")
    ) clk_div_5 (
        .CLKOUT (clk_pixel), // Pixel clock
        .HCLKIN (clk_tmds),
        .RESETN (rst_n),
        .CALIB  (1'b0)
    );

    // ========================================================================
    // 1. Synchronisms Generator (Timings)
    // ========================================================================

    video_timing #(
        .H_ACTIVE    (H_ACTIVE),
        .H_FRONT     (H_FRONT),
        .H_SYNC      (H_SYNC),
        .H_BACK      (H_BACK),
        .H_TOTAL     (H_TOTAL),
        .H_SYNC_POL  (H_SYNC_POL),
        .H_BITS      (H_BITS),

        .V_ACTIVE    (V_ACTIVE),
        .V_FRONT     (V_FRONT),
        .V_SYNC      (V_SYNC),
        .V_BACK      (V_BACK),
        .V_TOTAL     (V_TOTAL),
        .V_SYNC_POL  (V_SYNC_POL),
        .V_BITS      (V_BITS)
    ) timing_inst (
        .clk    (clk_pixel),
        .rst_n  (rst_n),
        .cx     (cx),
        .cy     (cy),
        .hsync  (hsync),
        .vsync  (vsync),
        .vde    (vde)
    );

    // ========================================================================
    // 2. VIS camera manager
    // ========================================================================
    // The visible manager:
    // - initializes the OV5640 through SCCB;
    // - receives a 160 x 120 YUV422 (stores Y8) or RGB565 (stores RGB332) DVP stream;
    // - converts RGB565 into RGB332;
    // - stores complete frames in the VIS double framebuffer;
    // - exposes the stable read bank through the read interface below.
    //
    // A Gowin_SDP_VIS IP from IP Catalog must be generated with:
    // data width:    8 bit
    // depth:         38400
    // address width: 16 bit
    // ========================================================================

    ov5640_visible_manager #(
        .IMG_W      (VIS_W),
        .IMG_H      (VIS_H),
        .FRAME_PIX  (VIS_FRAME_PIX),
        .ADDR_BITS  (VIS_ADDR_BITS),
        .VIS_Y8     (VIS_Y8)
    ) visible_camera_inst (
        .rst_n               (rst_n),
        .sys_clk             (clk_27MHz),

        .ov_pclk             (ov_pclk),
        .ov_vsync            (ov_vsync),
        .ov_href             (ov_href),
        .ov_data             (ov_data),

        .ov_reset_n          (ov_reset_n),   //different reset required for camera configuration
        .ov_pwdn             (ov_pwdn),

        .ov_scl              (ov_scl),
        .ov_sda              (ov_sda),

        // Read side: HDMI/fusion clock domain
        .rd_clk              (clk_pixel),
        .rd_swap_point       (hdmi_frame_start),
        .rd_req              (vis_rd_req),
        .rd_addr             (vis_rd_addr),
        .rd_pixel            (vis_rd_pixel),
        .rd_valid            (vis_rd_valid),

        .camera_initialized  (vis_camera_initialized),
        .frame_available     (vis_frame_available),
        .writing_allowed     (vis_writing_allowed)
    );

    // ========================================================================
    // 3. IR camera manager
    // ========================================================================
    // The infrared manager:
    // - receives the 16-bit serial thermal stream;
    // - discards the 23 footer words;
    // - converts each 16-bit thermal value into an 8-bit normalized intensity;
    // - stores complete 80 x 80 frames in the IR double framebuffer;
    // - exposes the stable read bank through the read interface below.

    // A Gowin_SDP_IR IP from IP Catalog must be generated with:
    // data width:    8 bit
    // depth:         12800
    // address width: 14 bit
    // ========================================================================
  
    vigil80_ir_manager #(
        .IMG_W         (IR_W),
        .IMG_H         (IR_H),
        .FRAME_PIX     (IR_FRAME_PIX),
        .FOOTER_WORDS  (IR_FOOTER_WORDS),
        .TOTAL_WORDS   (IR_TOTAL_WORDS),
        .ADDR_BITS     (IR_ADDR_BITS),

        .TEMP_MIN      (TEMP_MIN),
        .TEMP_SHIFT    (TEMP_SHIFT)
    ) vigil80_manager_inst (
        .rst_n            (rst_n),

        .vigil_sck        (vigil_sck),
        .vigil_csb        (vigil_csb),
        .vigil_mosi       (vigil_mosi),

        // Read side: HDMI/fusion clock domain
        .rd_clk           (clk_pixel),
        .rd_swap_point    (hdmi_frame_start),
        .rd_req           (ir_rd_req),
        .rd_addr          (ir_rd_addr),
        .rd_pixel         (ir_rd_pixel),
        .rd_valid         (ir_rd_valid),

        .frame_available  (ir_frame_available),
        .writing_allowed  (ir_writing_allowed)
    );
