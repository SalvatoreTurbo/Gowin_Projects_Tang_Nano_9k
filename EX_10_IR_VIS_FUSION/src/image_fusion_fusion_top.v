    // ========================================================================
    // 6. Display mode selection (button S2, active low)
    // ========================================================================
    // Each press selects the next mode: VIS -> IR gray -> IR colout -> 50/50 -> threshold -> VIS ...
    // The button is sampled once per HDMI frame (debounce + clean switch).
    // ========================================================================

    localparam int NUM_DISPLAY_MODES = 5;   // VIS, IR gray, IR colour, 50/50, threshold

    logic       btn_meta;       // synchronizer FF (debug_sel is asynchronous)
    logic       btn_prev;       // button level at the previous frame
    logic [2:0] display_mode;   // see fusion_pipeline for the list of modes

    always_ff @(posedge clk_pixel or negedge rst_n) begin
        if (!rst_n) begin
            btn_meta     <= 1'b1;
            btn_prev     <= 1'b1;
            display_mode <= 3'd0;      // VIS image after reset
        end
        else begin
            btn_meta <= debug_sel;

            if (hdmi_frame_start) begin
                btn_prev <= btn_meta;

                if (btn_prev && !btn_meta) begin     // released -> pressed
                    if (display_mode == NUM_DISPLAY_MODES - 1)
                        display_mode <= 3'd0;
                    else
                        display_mode <= display_mode + 3'd1;
                end
            end
        end
    end

    // ========================================================================
    // IMAGE-FUSION PIPELINE 
    // ========================================================================
    // Reads both framebuffers, aligns them (option B geometry) and drives
    // the HDMI RGB signals. Latency: 2 clk_pixel cycles.
    // ========================================================================

    fusion_pipeline #(
        .H_ACTIVE       (H_ACTIVE),
        .V_ACTIVE       (V_ACTIVE),
        .H_BITS         (H_BITS),
        .V_BITS         (V_BITS),

        .VIS_W          (VIS_W),
        .VIS_H          (VIS_H),
        .VIS_ADDR_BITS  (VIS_ADDR_BITS),
        .VIS_Y8         (VIS_Y8),

        .IR_W           (IR_W),
        .IR_H           (IR_H),
        .IR_ADDR_BITS   (IR_ADDR_BITS),

        .IR_COL_OFFSET  (0),
        .IR_ROW_OFFSET  (10),     // IR rows 10 ... 69 (centred window)

        // Mirror corrections: the VIGIL80 image is mirrored horizontally
        // with respect to the OV5640 image (vertical axis is correct)
        .VIS_MIRROR_X   (1'b0),
        .VIS_FLIP_Y     (1'b0),
        .IR_MIRROR_X    (1'b1),
        .IR_FLIP_Y      (1'b0),

        // Threshold-gated blend (mode 4)
        .IR_THRESHOLD   (8'd80),   // thermal gray level above which pixels are coloured
        .IR_ALPHA_Q     (3'd2)     // 2 = 50 % thermal colour
    ) fusion_pipeline_inst (
        .clk_pixel     (clk_pixel),
        .rst_n         (rst_n),

        .cx            (cx),
        .cy            (cy),
        .vde           (vde),

        .display_mode  (display_mode),

        .vis_rd_req    (vis_rd_req),
        .vis_rd_addr   (vis_rd_addr),
        .vis_rd_pixel  (vis_rd_pixel),
        .vis_rd_valid  (vis_rd_valid),

        .ir_rd_req     (ir_rd_req),
        .ir_rd_addr    (ir_rd_addr),
        .ir_rd_pixel   (ir_rd_pixel),
        .ir_rd_valid   (ir_rd_valid),

        .red           (red),
        .green         (green),
        .blue          (blue)
    );


    // =========================================================================
    // 7. TMDS ENCODER SECTION
    // =========================================================================

    // -------------------------------------------------------------------------
    // Pipeline alignment delay
    // -------------------------------------------------------------------------
    // The current fusion latency is 2 clk_pixel cycle
    // -------------------------------------------------------------------------

    logic [1:0] hsync_d, vsync_d, vde_d_top;

    always_ff @(posedge clk_pixel or negedge rst_n) begin
        if (!rst_n) begin
            hsync_d    <= 2'b00;
            vsync_d    <= 2'b00;
            vde_d_top  <= 2'b00;
        end
        else begin
            hsync_d    <= {hsync_d[0], hsync};
            vsync_d    <= {vsync_d[0], vsync};
            vde_d_top  <= {vde_d_top[0], vde};
        end
    end

    // Encoders TMDS
    tmds_encoder enc_b (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (blue),
        .ctrl      ({vsync_d[1], hsync_d[1]}), // The blue channel carries HSYNC and VSYNC during blanking, when vde = 0
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_b)
    );

    tmds_encoder enc_g (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (green),
        .ctrl      (2'b00),
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_g)
    );

    tmds_encoder enc_r (
        .clk       (clk_pixel),
        .rst_n     (rst_n),
        .data_in   (red),
        .ctrl      (2'b00),
        .vde       (vde_d_top[1]),
        .tmds_out  (tmds_r)
    );

    // ========================================================================
    // 8. Serializer 10:1
    // ========================================================================
    // The TMDS clock is serialized using the fixed pattern 1111100000.
    //
    // The Gowin OSER10 primitive uses:
    // - PCLK = pixel clock;
    // - FCLK = TMDS clock, equal to 5 times the pixel clock.
    // ========================================================================

    logic s_clk;
    logic s_d0;
    logic s_d1;
    logic s_d2;

    serializer_10to1 ser_b (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_b),
        .serial_out  (s_d0)
    );

    serializer_10to1 ser_g (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_g),
        .serial_out  (s_d1)
    );

    serializer_10to1 ser_r (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (tmds_r),
        .serial_out  (s_d2)
    );

    serializer_10to1 ser_clk (
        .rst_n       (rst_n),
        .clk_pixel   (clk_pixel),
        .clk_tmds    (clk_tmds),
        .data_in     (10'b1111100000),
        .serial_out  (s_clk)
    );

    // ========================================================================
    // Differential HDMI output buffers
    // ========================================================================
    // ELVDS_OBUF is required to generate the real physical differential output
    // pairs on the Tang Nano 9K
    // ========================================================================

    ELVDS_OBUF obuf_d0 (
        .I  (s_d0),
        .O  (tmds_d0_p),
        .OB (tmds_d0_n)
    );

    ELVDS_OBUF obuf_d1 (
        .I  (s_d1),
        .O  (tmds_d1_p),
        .OB (tmds_d1_n)
    );

    ELVDS_OBUF obuf_d2 (
        .I  (s_d2),
        .O  (tmds_d2_p),
        .OB (tmds_d2_n)
    );

    ELVDS_OBUF obuf_clk (
        .I  (s_clk),
        .O  (tmds_clk_p),
        .OB (tmds_clk_n)
    );

endmodule